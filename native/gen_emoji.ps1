# emoji/*.png (128px) -> emoji_data.h (48px, premultiplied ARGB)
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot
$N = 48
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// generated by gen_emoji.ps1 - premultiplied ARGB, ${N}x${N}")
[void]$sb.AppendLine("#define EMOJI_SRC $N")
foreach ($name in 'fire', 'coffee', 'pause') {
    $src = [System.Drawing.Image]::FromFile("$root\emoji\$name.png")
    $bmp = New-Object System.Drawing.Bitmap $N, $N, ([System.Drawing.Imaging.PixelFormat]::Format32bppPArgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.InterpolationMode = 'HighQualityBicubic'
    $g.PixelOffsetMode = 'HighQuality'
    $g.DrawImage($src, 0, 0, $N, $N)
    $g.Dispose(); $src.Dispose()
    $data = $bmp.LockBits((New-Object System.Drawing.Rectangle 0, 0, $N, $N), 'ReadOnly', 'Format32bppPArgb')
    $px = New-Object int[] ($N * $N)
    [System.Runtime.InteropServices.Marshal]::Copy($data.Scan0, $px, 0, $px.Length)
    $bmp.UnlockBits($data); $bmp.Dispose()
    [void]$sb.Append("static const unsigned int EMOJI_$($name.ToUpper())[$($N * $N)] = {")
    for ($i = 0; $i -lt $px.Length; $i++) {
        if ($i % 12 -eq 0) { [void]$sb.Append("`n ") }
        [void]$sb.Append(('0x{0:x8},' -f $px[$i]))
    }
    [void]$sb.AppendLine("`n};")
}
[System.IO.File]::WriteAllText("$PSScriptRoot\emoji_data.h", $sb.ToString())
"emoji_data.h generated"
